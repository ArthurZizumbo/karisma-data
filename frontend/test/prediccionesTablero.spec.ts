/**
 * US-026 - the predictive cards, their three levels and their four states.
 *
 * The components are mounted directly, with the real catalogues, and only the
 * transport is replaced. The `NuxtLink` double is declared here and not in
 * `test/i18nDePrueba.ts`: that helper is shared by several User Stories this
 * week and five duplicated lines cost less than a collision in a common file.
 */

const HISTORICO = publicado as unknown as PayloadHistoricos

const EnlaceStub = defineComponent({
  props: { to: { type: String, required: true } },
  template: '<a :href="to"><slot /></a>',
})

interface DesenlaceFetch {
  datos?: unknown
  error?: unknown
  estado?: 'idle' | 'pending' | 'success' | 'error'
}

/** Installs the `useFetch` double the composable loads the history through. */
function instalarFetch({ datos = null, error = null, estado = 'success' }: DesenlaceFetch) {
  const refresh = vi.fn(async () => undefined)
  vi.stubGlobal('useFetch', () => ({
    data: shallowRef(datos),
    error: ref(error),
    status: ref(estado),
    refresh,
  }))
  return { refresh }
}

/**
 * Mounts the section with the transport replaced.
 *
 * `adjuntar` puts the tree inside the document, which only the focus assertion
 * needs: `document.activeElement` stays on `<body>` for a detached tree, so
 * without it that test would measure the mount and not the behaviour.
 */
async function montarTablero(
  desenlace: DesenlaceFetch,
  idioma: CodigoIdioma = 'es',
  adjuntar = false,
) {
  const { refresh } = instalarFetch(desenlace)
  const wrapper = mount(TableroPredicciones, {
    attachTo: adjuntar ? document.body : undefined,
    global: {
      plugins: [crearI18nDePrueba(idioma)],
      components: { NuxtLink: EnlaceStub },
      stubs: { Icon: true },
    },
  })
  await flushPromises()
  return { wrapper, refresh }
}

/** The published payload with only the last `meses` months of every metric. */
function recortado(meses: number): PayloadHistoricos {
  return {
    ...HISTORICO,
    metricas: HISTORICO.metricas.map(metrica => ({
      ...metrica,
      puntos: metrica.puntos.slice(-meses),
    })),
  }
}

/**
 * Clicks needed to reach a revelation level, counted rather than promised.
 *
 * On every round it checks that the target level is NOT in the document, picks
 * the pending control with the lowest destination and presses it. It throws
 * past three presses, so a regression that buries a level shows up as a failure
 * and not as a slower test.
 */
async function abrirNivel(wrapper: VueWrapper, nivel: 2 | 3): Promise<number> {
  for (let pulsaciones = 0; pulsaciones <= 3; pulsaciones += 1) {
    if (wrapper.find(`[data-nivel="${nivel}"]`).exists()) {
      return pulsaciones
    }
    const pendientes = wrapper
      .findAll('[data-accion-revelacion]')
      .map(nodo => ({ nodo, destino: Number(nodo.attributes('data-nivel-destino')) }))
      .filter(
        ({ destino }) =>
          destino <= nivel && !wrapper.find(`[data-nivel="${destino}"]`).exists(),
      )
      .sort((izquierda, derecha) => izquierda.destino - derecha.destino)

    const siguiente = pendientes[0]
    if (siguiente === undefined) {
      throw new Error(`No hay ningun control que lleve al nivel ${nivel}`)
    }
    await siguiente.nodo.trigger('click')
    await flushPromises()
  }
  throw new Error(`El nivel ${nivel} no se alcanzo en tres pulsaciones`)
}

/** Monthly points of a perfect line, oldest first. */
function recta(puntos: number): PuntoMensual[] {
  let mes = '2024-07'
  return Array.from({ length: puntos }, (_, indice) => {
    const punto: PuntoMensual = { mes, valor: 2 * indice + 1 }
    mes = mesSiguiente(mes)
    return punto
  })
}

