def generar_arquitectura_informacion(
        audience_label='evaluadores prototipo',
        output_name='a3_arquitectura_informacion.png'):
    """Draw the revised information architecture and its cross-cutting facets."""
    fig, ax = plt.subplots(figsize=(8.0, 10.6))

    label_w = 25.0
    col_w = (100.0 - label_w) / 4.0
    centers = [label_w + col_w / 2 + i * col_w for i in range(4)]
    box_w = col_w - 2.0

    def band_label(text, y):
        ax.text(0.5, y, text, ha='left', va='center', color=COLOR_MUTED,
                fontsize=7.5, fontweight='bold', linespacing=1.6)

    # Fila 1: necesidades por perfil
    y_need, h_need = 90.0, 6.5
    band_label('NECESIDADES\nPOR PERFIL', y_need + h_need / 2)
    for cx, texto in zip(centers, NECESIDADES):
        draw_box(ax, cx - box_w / 2, y_need, box_w, h_need, COLOR_NAVY,
                 COLOR_NAVY, lw=1.4)
        ax.text(cx, y_need + h_need / 2, texto, ha='center', va='center',
                color='white', fontsize=7.5, fontweight='bold', zorder=10,
                linespacing=1.4)

    # Fila 2: tareas
    y_task, h_task = 81.0, 6.0
    band_label('TAREAS', y_task + h_task / 2)
    for cx, texto in zip(centers, TAREAS):
        ax.plot([cx, cx], [y_need, y_task + h_task], color=COLOR_MUTED,
                lw=1.1, zorder=2)
        draw_box(ax, cx - box_w / 2, y_task, box_w, h_task, COLOR_SKY_SOFT,
                 COLOR_NAVY, lw=1.1)
        ax.text(cx, y_task + h_task / 2, texto, ha='center', va='center',
                color=COLOR_NAVY, fontsize=7.5, fontweight='bold', zorder=10,
                linespacing=1.4)

    # Fila 3: categorías de la arquitectura revisada
    y_cat, h_cat = 73.0, 5.0
    band_label('CATEGORÍAS\n(ARQUITECTURA\nREVISADA)', y_cat + h_cat / 2)
    for cx, modulo in zip(centers, REVISED_TREE):
        ax.plot([cx, cx], [y_task, y_cat + h_cat], color=COLOR_MUTED, lw=1.1,
                zorder=2)
        changed = modulo['changed']
        draw_box(ax, cx - box_w / 2, y_cat, box_w, h_cat,
                 COLOR_AMBER if changed else COLOR_SKY,
                 COLOR_AMBER_DARK if changed else COLOR_NAVY,
                 lw=2.0 if changed else 1.1)
        ax.text(cx, y_cat + h_cat / 2, textwrap.fill(modulo['titulo'], 16),
                ha='center', va='center', color='white', fontsize=8,
                fontweight='bold', zorder=10, linespacing=1.4)

    # Fila 4: objetos de información
    y_obj_top = 70.0
    obj_h, obj_gap = 4.0, 1.0
    band_label('OBJETOS DE\nINFORMACIÓN', y_obj_top - 2.4 * (obj_h + obj_gap))
    for cx, modulo in zip(centers, REVISED_TREE):
        y_top = y_obj_top
        for hijo in modulo['hijos']:
            y0 = y_top - obj_h
            changed = hijo['changed']
            ax.plot([cx, cx], [y0 + obj_h, y_top], color=COLOR_MUTED, lw=1.0,
                    ls=':', zorder=2)
            draw_box(ax, cx - box_w / 2, y0, box_w, obj_h,
                     COLOR_AMBER_SOFT if changed else 'white',
                     COLOR_AMBER if changed else COLOR_MUTED,
                     lw=2.0 if changed else 1.0)
            if changed:
                draw_change_band(ax, cx - box_w / 2, y0, 1.3, obj_h)
            ax.text(cx + (0.7 if changed else 0.0), y0 + obj_h / 2,
                    textwrap.fill(hijo['titulo'], 20), ha='center',
                    va='center', color=COLOR_NAVY, fontsize=7, zorder=10,
                    linespacing=1.4)
            y_top = y0 - obj_gap

    # Fila 5: facetas transversales de etiquetado múltiple
    y_band = 41.5
    ax.plot([0.5, 99.5], [y_band + 2.6, y_band + 2.6], color=COLOR_AMBER,
            lw=1.2, ls=(0, (5, 4)), zorder=2)
    ax.text(0.5, y_band, 'FACETAS TRANSVERSALES (ETIQUETADO MÚLTIPLE)',
            ha='left', va='center', color=COLOR_AMBER_DARK, fontsize=8.5,
            fontweight='bold')
    ax.text(0.5, y_band - 2.4,
            f'Tarjetas que los {audience_label} pidieron colocar en dos o '
            'más grupos a la vez: cada una vive en un nodo principal\ny se '
            'alcanza además desde otra categoría, de modo que cruza la '
            'jerarquía en lugar de duplicarse. El relleno ámbar\nde arriba '
            'marca los nodos modificados tras la prueba de árbol.',
            ha='left', va='top', color=COLOR_MUTED, fontsize=7,
            linespacing=1.7)

    y_head = 31.0
    for cx, modulo in zip(centers, REVISED_TREE):
        ax.text(cx, y_head, textwrap.fill(modulo['titulo'], 14), ha='center',
                va='center', color=COLOR_NAVY, fontsize=7.5,
                fontweight='bold', linespacing=1.4)
    ax.text(0.5, y_head, 'Faceta', ha='left', va='center', color=COLOR_NAVY,
            fontsize=7.5, fontweight='bold')
    ax.text(label_w - 1.0, y_head, 'Duplicados', ha='right', va='center',
            color=COLOR_NAVY, fontsize=7.5, fontweight='bold')
    ax.plot([0.5, 99.5], [y_head - 2.6, y_head - 2.6], color=COLOR_NAVY,
            lw=1.1, zorder=2)

    y_row = y_head - 5.0
    for nombre, conteo, principal, cruces in FACETAS:
        ax.plot([0.5, 99.5], [y_row - 1.25, y_row - 1.25], color='#E2E8F0',
                lw=0.8, zorder=1)
        ax.text(0.5, y_row, nombre, ha='left', va='center', color=COLOR_NAVY,
                fontsize=7)
        ax.text(label_w - 1.0, y_row, '%d de 8' % conteo, ha='right',
                va='center', color=COLOR_MUTED, fontsize=7)
        for idx, cx in enumerate(centers):
            if idx == principal:
                ax.plot([cx], [y_row], marker='s', markersize=7,
                        color=COLOR_NAVY, zorder=6)
            elif idx in cruces:
                ax.plot([cx], [y_row], marker='o', markersize=7,
                        markerfacecolor='white', markeredgecolor=COLOR_AMBER,
                        markeredgewidth=2.0, zorder=6)
        y_row -= 2.5

    # Leyenda de marcadores
    y_leg = y_row - 0.6
    ax.plot([1.5], [y_leg], marker='s', markersize=7, color=COLOR_NAVY,
            zorder=6)
    ax.text(3.5, y_leg, 'Ubicación principal en la arquitectura revisada',
            ha='left', va='center', color=COLOR_NAVY, fontsize=7)
    ax.plot([52.0], [y_leg], marker='o', markersize=7, markerfacecolor='white',
            markeredgecolor=COLOR_AMBER, markeredgewidth=2.0, zorder=6)
    ax.text(54.0, y_leg, 'Acceso cruzado por etiquetado múltiple',
            ha='left', va='center', color=COLOR_AMBER_DARK, fontsize=7)

    ax.set_title('Arquitectura de información de Karisma Data\n'
                 '(versión revisada tras la prueba de árbol)',
                 fontsize=13, fontweight='bold', color=COLOR_NAVY, pad=12)
    ax.set_xlim(0, 100)
    ax.set_ylim(0, 100)
    ax.axis('off')

    plt.tight_layout()
    plt.savefig(f'figuras/{output_name}', dpi=300,
                bbox_inches='tight')
    plt.close()


