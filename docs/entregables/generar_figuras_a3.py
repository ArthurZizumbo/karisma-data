def generar_mapa_navegacion():
    """Draw the revised site map as a left to right tree (portrait friendly)."""
    fig, ax = plt.subplots(figsize=(8.2, 10.2))

    # Geometría de las tres columnas: raíz, módulos, segundo nivel.
    root_x, root_w = 1.0, 16.0
    mod_x, mod_w = 19.5, 23.0
    root_bus_x = 17.2
    child_bus_x = 44.5
    child_x, child_w = 48.5, 50.5
    cross_x = 46.5

    box_h, gap, group_gap = 4.0, 0.85, 1.8
    y_cursor = 98.0

    mod_centers = []
    child_centers = {}

    # Primera pasada: reservar el espacio vertical de cada módulo.
    for modulo in REVISED_TREE:
        centros = []
        for hijo in modulo['hijos']:
            y0 = y_cursor - box_h
            centros.append(y0 + box_h / 2)
            y_cursor = y0 - gap
        child_centers[modulo['titulo']] = centros
        mod_centers.append((centros[0] + centros[-1]) / 2)
        y_cursor -= group_gap

    # Raíz
    root_cy = (mod_centers[0] + mod_centers[-1]) / 2
    root_h = 11.0
    draw_box(ax, root_x, root_cy - root_h / 2, root_w, root_h, COLOR_NAVY,
             COLOR_NAVY, lw=1.8)
    ax.text(root_x + root_w / 2, root_cy,
            'Karisma Data\n\nPortal de datos\nfinancieros',
            ha='center', va='center', color='white', fontsize=8.5,
            fontweight='bold', zorder=10, linespacing=1.4)
    ax.plot([root_x + root_w, root_bus_x], [root_cy, root_cy],
            color=COLOR_MUTED, lw=1.2, zorder=2)
    ax.plot([root_bus_x, root_bus_x], [mod_centers[0], mod_centers[-1]],
            color=COLOR_MUTED, lw=1.2, zorder=2)

    bitacora_cy = None
    mod3_bottom = None

    for modulo, mod_cy in zip(REVISED_TREE, mod_centers):
        centros = child_centers[modulo['titulo']]
        changed = modulo['changed']
        mod_h = min(10.0, centros[0] - centros[-1] + box_h)
        mod_y = mod_cy - mod_h / 2

        ax.plot([root_bus_x, mod_x], [mod_cy, mod_cy], color=COLOR_MUTED,
                lw=1.2, zorder=2)
        draw_box(ax, mod_x, mod_y, mod_w, mod_h,
                 COLOR_AMBER if changed else COLOR_NAVY,
                 COLOR_AMBER_DARK if changed else COLOR_NAVY,
                 lw=2.4 if changed else 1.4)
        ax.text(mod_x + mod_w / 2, mod_cy, textwrap.fill(modulo['titulo'], 15),
                ha='center', va='center', color='white', fontsize=10.5,
                fontweight='bold', zorder=10, linespacing=1.4)
        if modulo['titulo'].startswith('3.'):
            mod3_bottom = mod_y

        # Bus vertical del módulo hacia sus hijos
        ax.plot([mod_x + mod_w, child_bus_x], [mod_cy, mod_cy],
                color=COLOR_MUTED, lw=1.2, zorder=2)
        ax.plot([child_bus_x, child_bus_x], [centros[0], centros[-1]],
                color=COLOR_MUTED, lw=1.2, zorder=2)

        for hijo, cy in zip(modulo['hijos'], centros):
            hijo_changed = hijo['changed']
            y0 = cy - box_h / 2
            ax.plot([child_bus_x, child_x], [cy, cy], color=COLOR_MUTED,
                    lw=1.2, zorder=2)
            draw_box(ax, child_x, y0, child_w, box_h,
                     COLOR_AMBER_SOFT if hijo_changed else COLOR_SKY_SOFT,
                     COLOR_AMBER if hijo_changed else COLOR_NAVY,
                     lw=2.2 if hijo_changed else 1.2)
            texto_x = child_x + 1.4
            if hijo_changed:
                draw_change_band(ax, child_x, y0, 1.5, box_h)
                texto_x = child_x + 2.6
            if hijo['detalle']:
                ax.text(texto_x, y0 + box_h - 0.8,
                        hijo['titulo'], ha='left', va='top', color=COLOR_NAVY,
                        fontsize=9, fontweight='bold', zorder=10)
                ax.text(texto_x, y0 + box_h - 2.1,
                        textwrap.fill(hijo['detalle'], 76), ha='left',
                        va='top', color=COLOR_MUTED, fontsize=7,
                        zorder=10, linespacing=1.35)
            else:
                ax.text(texto_x, cy, hijo['titulo'], ha='left', va='center',
                        color=COLOR_NAVY, fontsize=9, fontweight='bold',
                        zorder=10)
            if hijo['titulo'].startswith('4.3'):
                bitacora_cy = cy

    # Acceso cruzado: Gobierno del dato -> 4.3 Bitácora de accesos
    ax.plot([mod_x + mod_w, cross_x], [mod3_bottom, mod3_bottom],
            color=COLOR_AMBER, lw=1.8, ls=(0, (3.5, 2.5)), zorder=8)
    ax.plot([cross_x, cross_x], [mod3_bottom, bitacora_cy], color=COLOR_AMBER,
            lw=1.8, ls=(0, (3.5, 2.5)), zorder=8)
    ax.annotate('', xy=(child_x, bitacora_cy), xytext=(cross_x, bitacora_cy),
                arrowprops=dict(arrowstyle='-|>', color=COLOR_AMBER, lw=1.8,
                                shrinkA=0, shrinkB=0), zorder=8)
    ax.text(cross_x - 0.8, (mod3_bottom + bitacora_cy) / 2, 'acceso cruzado',
            rotation=90, ha='center', va='center', color=COLOR_AMBER_DARK,
            fontsize=7.5, fontweight='bold', zorder=10,
            bbox=dict(boxstyle='square,pad=0.15', facecolor='white',
                      edgecolor='none'))

    # Leyenda
    leg_x, leg_y, leg_w, leg_h = 1.0, 1.0, 98.0, 12.0
    draw_box(ax, leg_x, leg_y, leg_w, leg_h, COLOR_PAPER, COLOR_MUTED, lw=1.0,
             zorder=3)
    sw_y = leg_y + leg_h - 3.4
    draw_box(ax, leg_x + 2.0, sw_y, 6.0, 2.4, COLOR_AMBER_SOFT, COLOR_AMBER,
             lw=2.2, zorder=6)
    draw_change_band(ax, leg_x + 2.0, sw_y, 1.1, 2.4)
    ax.text(leg_x + 9.5, sw_y + 1.2,
            'El ámbar marca los cambios aplicados tras la prueba de árbol.',
            ha='left', va='center', color=COLOR_AMBER_DARK, fontsize=9,
            fontweight='bold', zorder=10)
    ax.text(leg_x + 2.0, leg_y + leg_h - 4.6,
            'Cambio 1: los tableros e indicadores de riesgo pasaron de '
            'Gobierno a Exploración (la tarea 3 acertó 1 de 8).\n'
            'Cambio 2: la categoría 3 se renombró Gobierno del dato al salir '
            'los tableros.\n'
            'Cambio 3: la bitácora de accesos permanece en Administración y '
            'recibe un acceso cruzado desde Gobierno\ndel dato (los 8 '
            'evaluadores titubearon en la tarea 4).',
            ha='left', va='top', color=COLOR_NAVY, fontsize=7.5, zorder=10,
            linespacing=1.7)

    ax.set_title('Mapa de navegación de Karisma Data\n'
                 '(versión revisada tras la prueba de árbol)',
                 fontsize=13, fontweight='bold', color=COLOR_NAVY, pad=12)
    ax.set_xlim(0, 100)
    ax.set_ylim(0, 100)
    ax.axis('off')

    plt.tight_layout()
    plt.savefig('figuras/a3_mapa_sitio.png', dpi=300, bbox_inches='tight')
    plt.close()


