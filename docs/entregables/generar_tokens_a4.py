@dataclass(frozen=True)
class Color:
    """A colour parsed from uxdoc.sty."""

    nombre_tex: str
    hex: str


@dataclass(frozen=True)
class Tono:
    """One step of a colour family, or one standalone token of the system."""

    nombre: str
    tono: int
    color: Color
    es_ancla: bool
    uso: str
    reusa: str | None = None

    @property
    def clase(self) -> str:
        """Tailwind utility that proves the token reaches the interface."""
        return f"bg-{self.nombre}"


@dataclass(frozen=True)
class Familia:
    """A five step colour family of the design system."""

    clave: str
    etiqueta: str
    tonos: tuple[Tono, ...]


@dataclass(frozen=True)
class Alias:
    """A US-001 token kept by name and derived from a step of the scale."""

    nombre: str
    origen: str
    tono: Tono


@dataclass(frozen=True)
class ParContraste:
    """A verified foreground/background pair."""

    frente: Tono
    fondo: Tono
    ratio: float
    veredicto: Veredicto
    regla: str


@dataclass(frozen=True)
class Hallazgo:
    """A contrast defect of the matrix together with the rule that replaces it."""

    numero: int
    par: ParContraste
    sustituto: ParContraste
    diagnostico: str


@dataclass(frozen=True)
class RolTipografico:
    """One of the nine roles of the type scale."""

    clave: str
    etiqueta: str
    tamano_px: int
    interlinea_px: int
    peso: int
    familia: str
    espaciado_em: float
    uso: str

    @property
    def clase(self) -> str:
        """Tailwind utility generated by the token."""
        return f"text-{self.clave}"


@dataclass(frozen=True)
class Sistema:
    """The whole design system, derived from a single stylesheet."""

    familias: tuple[Familia, ...]
    neutros: tuple[Tono, ...]
    semanticos: tuple[Tono, ...]
    series: tuple[Tono, ...]
    alias: tuple[Alias, ...]
    contrastes: tuple[ParContraste, ...]
    hallazgos: tuple[Hallazgo, ...]
    tipografia: tuple[RolTipografico, ...]

    @property
    def tokens(self) -> tuple[Tono, ...]:
        """Every colour token, in the order the guide prints them."""
        de_familias = tuple(tono for familia in self.familias for tono in familia.tonos)
        return de_familias + self.neutros + self.semanticos + self.series

    def tono(self, nombre: str) -> Tono:
        """Return the token named ``nombre``.

        Args:
            nombre: CSS token name without the ``--color-`` prefix.

        Returns:
            The matching token.

        Raises:
            KeyError: if no token carries that name.
        """
        for candidato in self.tokens:
            if candidato.nombre == nombre:
                return candidato
        raise KeyError(f"token de color desconocido: {nombre}")


