def leer_definecolor(ruta: Path) -> dict[str, Color]:
    r"""Read every colour declaration of the stylesheet, in file order.

    Both forms are read. ``\\definecolor`` declares a value; ``\\colorlet``
    declares an alias and resolves to the very same object, so a reused colour
    cannot drift from the anchor it reuses.

    Args:
        ruta: Path of uxdoc.sty, the single source of colour.

    Returns:
        Mapping from TeX colour name to the parsed colour.

    Raises:
        ValueError: if an alias points at a name that was not declared before.
    """
    colores: dict[str, Color] = {}
    for linea in ruta.read_text(encoding="utf-8").splitlines():
        limpia = PATRON_COMENTARIO.sub("", linea)
        declaracion = PATRON_DEFINECOLOR.search(limpia)
        if declaracion is not None:
            nombre, valor = declaracion.groups()
            colores[nombre] = Color(nombre_tex=nombre, hex=ALMOHADILLA + valor.upper())
            continue
        alias = PATRON_COLORLET.search(limpia)
        if alias is not None:
            nombre, origen = alias.groups()
            if origen not in colores:
                raise ValueError(
                    f"el alias {nombre} apunta a {origen}, que no esta declarado"
                )
            colores[nombre] = colores[origen]
    return colores


def luminancia_relativa(hex_color: str) -> float:
    """Relative luminance of a colour, as defined by WCAG 2.x.

    Args:
        hex_color: Colour in six digit hexadecimal notation with a leading hash.

    Returns:
        Relative luminance between 0 and 1.
    """
    crudo = hex_color.lstrip(ALMOHADILLA)
    canales = [int(crudo[posicion : posicion + 2], 16) / 255 for posicion in (0, 2, 4)]
    lineales = [
        canal / 12.92 if canal <= 0.03928 else ((canal + 0.055) / 1.055) ** 2.4
        for canal in canales
    ]
    return 0.2126 * lineales[0] + 0.7152 * lineales[1] + 0.0722 * lineales[2]


def razon_de_contraste(frente: str, fondo: str) -> float:
    """Contrast ratio of two colours, as defined by WCAG 2.x.

    Args:
        frente: Foreground colour in hexadecimal notation.
        fondo: Background colour in hexadecimal notation.

    Returns:
        Ratio between 1 and 21. The order of the arguments does not matter.
    """
    luminancias = (luminancia_relativa(frente), luminancia_relativa(fondo))
    return (max(luminancias) + 0.05) / (min(luminancias) + 0.05)


def _veredicto(ratio: float) -> Veredicto:
    """Classify a rounded ratio against the WCAG 2.x thresholds."""
    if ratio >= 7.0:
        return "AAA"
    if ratio >= 4.5:
        return "AA"
    if ratio >= 3.0:
        return "AA-grande"
    return "falla"


def _rgb(color: Color) -> str:
    """Space separated RGB channels of a colour, for the CSS shadow syntax."""
    crudo = color.hex.lstrip(ALMOHADILLA)
    canales = (int(crudo[posicion : posicion + 2], 16) for posicion in (0, 2, 4))
    return " ".join(str(canal) for canal in canales)


def _tomar(colores: dict[str, Color], nombre_tex: str) -> Color:
    """Return a declared colour or fail loudly.

    Args:
        colores: Colours parsed from the stylesheet.
        nombre_tex: Name the specification expects to find.

    Returns:
        The declared colour.

    Raises:
        ValueError: if the stylesheet does not declare that name.
    """
    if nombre_tex not in colores:
        raise ValueError(
            f"uxdoc.sty no declara {nombre_tex}: la escala y la fuente divergieron"
        )
    return colores[nombre_tex]


def _duenos() -> dict[str, str]:
    r"""Map every TeX colour name to the token that declares it as its own.

    An alias declared with ``\\colorlet`` resolves to the anchor object, so a
    token whose parsed name differs from the one its specification declares is
    reusing the token that owns that name. The map makes the reuse explicit in
    the guide instead of leaving it as a coincidence of equal values.

    Returns:
        Mapping from TeX colour name to CSS token name.
    """
    mapa: dict[str, str] = {}
    for clave, _, espec_tonos in ESPEC_FAMILIAS:
        for tono, nombre_tex, _uso in espec_tonos:
            mapa[nombre_tex] = f"{clave}-{tono}"
    for espec in (*ESPEC_NEUTROS, *ESPEC_SEMANTICOS, *ESPEC_SERIES):
        nombre, _tono, nombre_tex, _uso = espec
        mapa[nombre_tex] = nombre
    return mapa


def _construir_token(colores: dict[str, Color], espec: EspecToken) -> Tono:
    """Build one standalone token of the system from its specification."""
    nombre, tono, nombre_tex, uso = espec
    color = _tomar(colores, nombre_tex)
    reusa = _duenos().get(color.nombre_tex) if color.nombre_tex != nombre_tex else None
    return Tono(
        nombre=nombre,
        tono=tono,
        color=color,
        es_ancla=color.nombre_tex in ANCLAS,
        uso=uso,
        reusa=reusa,
    )


def construir_sistema(colores: dict[str, Color]) -> Sistema:
    """Assemble the design system from the parsed colours.

    Args:
        colores: Colours parsed from uxdoc.sty.

    Returns:
        The whole system: families, neutrals, semantics, series, aliases,
        contrast matrix, findings and type scale.

    Raises:
        ValueError: if the stylesheet lost an anchor, if a family stops being
            monotonic or if the token count leaves the 37 of the guide.
    """
    faltantes = [ancla for ancla in ANCLAS if ancla not in colores]
    if faltantes:
        raise ValueError(f"uxdoc.sty perdio anclas versionadas: {faltantes}")

    familias: list[Familia] = []
    for clave, etiqueta, espec_tonos in ESPEC_FAMILIAS:
        tonos = [
            _construir_token(colores, (f"{clave}-{tono}", tono, nombre_tex, uso))
            for tono, nombre_tex, uso in espec_tonos
        ]
        luminancias = [luminancia_relativa(paso.color.hex) for paso in tonos]
        if any(anterior <= siguiente for anterior, siguiente in pairwise(luminancias)):
            raise ValueError(
                f"la familia {clave} no oscurece de forma monotona del 100 al 900"
            )
        familias.append(Familia(clave=clave, etiqueta=etiqueta, tonos=tuple(tonos)))

    neutros = tuple(_construir_token(colores, espec) for espec in ESPEC_NEUTROS)
    semanticos = tuple(_construir_token(colores, espec) for espec in ESPEC_SEMANTICOS)
    series = tuple(_construir_token(colores, espec) for espec in ESPEC_SERIES)

    parcial = Sistema(
        familias=tuple(familias),
        neutros=neutros,
        semanticos=semanticos,
        series=series,
        alias=(),
        contrastes=(),
        hallazgos=(),
        tipografia=ESPEC_TIPOGRAFIA,
    )

    esperados = 5 * len(ESPEC_FAMILIAS) + len(neutros) + len(semanticos) + len(series)
    if len(parcial.tokens) != esperados:
        raise ValueError(f"el sistema declara {len(parcial.tokens)} tokens de color")

    anclas_vivas = {
        token.color.nombre_tex for token in parcial.tokens if token.es_ancla
    }
    if anclas_vivas != set(ANCLAS):
        raise ValueError(
            "la escala dejo de usar alguna de las once anclas versionadas: "
            f"{sorted(set(ANCLAS) - anclas_vivas)}"
        )

    alias = tuple(
        Alias(nombre=nombre, origen=origen, tono=parcial.tono(origen))
        for nombre, origen in ESPEC_ALIAS
    )
    contrastes = tuple(
        _par(parcial, frente, fondo, regla) for frente, fondo, regla in ESPEC_PARES
    )
    hallazgos = tuple(
        Hallazgo(
            numero=numero,
            par=_buscar_par(contrastes, frente, fondo),
            sustituto=_buscar_par(contrastes, frente_ok, fondo_ok),
            diagnostico=diagnostico,
        )
        for numero, frente, fondo, frente_ok, fondo_ok, diagnostico in ESPEC_HALLAZGOS
    )

    return Sistema(
        familias=parcial.familias,
        neutros=neutros,
        semanticos=semanticos,
        series=series,
        alias=alias,
        contrastes=contrastes,
        hallazgos=hallazgos,
        tipografia=ESPEC_TIPOGRAFIA,
    )


def _par(sistema: Sistema, frente: str, fondo: str, regla: str) -> ParContraste:
    """Measure one foreground/background pair of the matrix."""
    tono_frente = sistema.tono(frente)
    tono_fondo = sistema.tono(fondo)
    ratio = round(razon_de_contraste(tono_frente.color.hex, tono_fondo.color.hex), 2)
    return ParContraste(
        frente=tono_frente,
        fondo=tono_fondo,
        ratio=ratio,
        veredicto=_veredicto(ratio),
        regla=regla,
    )


def _buscar_par(
    contrastes: tuple[ParContraste, ...], frente: str, fondo: str
) -> ParContraste:
    """Return the measured pair with those two tokens.

    Args:
        contrastes: Matrix already measured.
        frente: Foreground token name.
        fondo: Background token name.

    Returns:
        The matching pair.

    Raises:
        ValueError: if the matrix does not cover the pair a finding cites.
    """
    for par in contrastes:
        if par.frente.nombre == frente and par.fondo.nombre == fondo:
            return par
    raise ValueError(f"la matriz no mide el par {frente} sobre {fondo}")


def _cabecera(marca: str) -> list[str]:
    """Build the "generated, do not edit" banner shared by the four outputs.

    Args:
        marca: Comment prefix of the target language.

    Returns:
        The banner lines, already prefixed and without trailing spaces.
    """
    cuerpo = (
        f"Guia de estilos de Karisma Data {VERSION_GUIA} - {FECHA_GUIA}",
        "",
        "GENERADO. No editar a mano: cualquier cambio se pierde en la siguiente",
        "corrida y hace divergir la aplicacion del PDF del curso.",
        "",
        "Fuente unica: docs/entregables/estilo/uxdoc.sty",
        "Generador:    docs/entregables/generar_tokens_a4.py",
        "Regenerar:    make tokens",
        "Verificar:    python docs/entregables/generar_tokens_a4.py --verificar",
    )
    return [f"{marca} {texto}".rstrip() for texto in cuerpo]


def emitir_theme_css(sistema: Sistema) -> str:
    """Render the palette of the report as a Tailwind v4 ``@theme`` block.

    Nothing writes this anywhere. ``frontend/app/assets/css/main.css`` belongs
    to ``design/emitir.py``, and pointing this text back at it is the defect
    that ``docs/us-backlog/11-make-tokens-destruye-los-tokens-del-portal.md``
    describes. It stays because the contract tests read it to check that every
    alias of US-001 takes its value from its step of the scale.

    Args:
        sistema: The design system.

    Returns:
        The palette of the report written as a ``@theme`` block.
    """
    lineas: list[str] = [
        "/* Paleta del informe en forma de @theme - generado, no editar a mano */",
        "/*",
        *_cabecera(" *"),
        " *",
        " * Esta hoja NO es la del portal: main.css sale de design/sistema.py y",
        " * lo publica design/emitir.py. Aqui la derivacion va en un solo",
        " * sentido, uxdoc.sty -> laminas -> PDF, y nada fluye hacia atras.",
        " */",
        '@import "tailwindcss";',
        "",
        "@theme {",
    ]

    def bloque(titulo: str) -> None:
        lineas.append(f"  /* {titulo} */")

    def token(nombre: str, valor: str, nota: str) -> None:
        declaracion = f"  --{nombre}: {valor};"
        lineas.append(f"{declaracion:<40} /* {nota} */")

    def color(tono: Tono) -> None:
        marca = " (ancla)" if tono.es_ancla else ""
        reuso = f" (= {tono.reusa})" if tono.reusa else ""
        token(
            f"color-{tono.nombre}",
            tono.color.hex,
            f"{tono.color.nombre_tex}{marca}{reuso} - {tono.uso}",
        )

    for familia in sistema.familias:
        bloque(familia.etiqueta)
        for paso in familia.tonos:
            color(paso)
        lineas.append("")

    for titulo, grupo in (
        ("Neutros - sin negro ni blanco puros", sistema.neutros),
        ("Semanticos - el aviso y el informativo reusan la escala", sistema.semanticos),
        (
            "Serie categorica de grafica - todas con 3:1 o mas sobre la superficie",
            sistema.series,
        ),
    ):
        bloque(titulo)
        for tono in grupo:
            color(tono)
        lineas.append("")

    bloque("Alias de US-001 - derivados de la escala, nunca escritos aparte")
    for alias in sistema.alias:
        token(f"color-{alias.nombre}", alias.tono.color.hex, f"= {alias.origen}")
    lineas.append("")

    bloque("Tipografia - dos familias servidas desde el propio origen")
    token("font-display", '"Lexend Deca", sans-serif', "Titulares")
    token("font-sans", '"Fira Sans", sans-serif', "Cuerpo")
    lineas.append("")

    bloque("Escala tipografica - 9 roles. El peso no construye jerarquia")
    for rol in sistema.tipografia:
        token(f"text-{rol.clave}", f"{rol.tamano_px}px", rol.uso)
        lineas.append(f"  --text-{rol.clave}--line-height: {rol.interlinea_px}px;")
        lineas.append(f"  --text-{rol.clave}--font-weight: {rol.peso};")
        if rol.espaciado_em:
            lineas.append(
                f"  --text-{rol.clave}--letter-spacing: {rol.espaciado_em}em;"
            )
    lineas.append("")

    bloque(
        "Ritmo de espaciado en base 4: Tailwind deriva "
        + "/".join(str(paso) for paso in ESCALA_ESPACIADO)
    )
    token("spacing", f"{ESCALA_ESPACIADO[0]}px", "unidad del ritmo")
    lineas.append("")

    bloque("Radios")
    for nombre, valor, uso in ESPEC_RADIOS:
        token(f"radius-{nombre}", f"{valor}px", uso)
    lineas.append("")

    tinta = sistema.tono("ink-strong").color
    bloque("Sombras - un solo color de sombra, la tinta mas oscura del sistema")
    for (nombre, desplazamiento, uso), opacidad in zip(
        ESPEC_SOMBRAS, ESPEC_OPACIDAD_SOMBRA, strict=True
    ):
        token(
            f"shadow-{nombre}",
            f"{desplazamiento} rgb({_rgb(tinta)} / {opacidad})",
            uso,
        )
    lineas.append("")

    bloque("Puntos de quiebre")
    for nombre, valor, uso in ESPEC_QUIEBRES:
        token(f"breakpoint-{nombre}", f"{valor}px", uso)
    lineas.append("")

    bloque("Densidad - ficha Data-Dense Dashboard de ui-ux-pro-max")
    for nombre, valor, uso in ESPEC_DENSIDAD:
        token(nombre, f"{valor}px", uso)

    lineas.append("}")
    return "\n".join(lineas) + "\n"


def _cadena_ts(texto: str) -> str:
    """Quote a Spanish string for TypeScript, escaping what the linter forbids."""
    escapado = texto.replace("\\", "\\\\").replace("'", "\\'")
    return f"'{escapado}'"


def _tono_ts(tono: Tono, sangria: str) -> list[str]:
    """Serialise one token as a TypeScript object literal."""
    lineas = [
        f"{sangria}{{",
        f"{sangria}  nombre: {_cadena_ts(tono.nombre)},",
        f"{sangria}  tono: {tono.tono},",
        f"{sangria}  hex: {_cadena_ts(tono.color.hex)},",
        f"{sangria}  clase: {_cadena_ts(tono.clase)},",
        f"{sangria}  nombreTex: {_cadena_ts(tono.color.nombre_tex)},",
        f"{sangria}  esAncla: {'true' if tono.es_ancla else 'false'},",
        f"{sangria}  reusa: {_cadena_ts(tono.reusa) if tono.reusa else 'null'},",
        f"{sangria}  uso: {_cadena_ts(tono.uso)},",
        f"{sangria}}},",
    ]
    return lineas


def _par_ts(par: ParContraste, sangria: str) -> list[str]:
    """Serialise one contrast pair as a TypeScript object literal."""
    return [
        f"{sangria}{{",
        f"{sangria}  frente: {_cadena_ts(par.frente.nombre)},",
        f"{sangria}  frenteHex: {_cadena_ts(par.frente.color.hex)},",
        f"{sangria}  fondo: {_cadena_ts(par.fondo.nombre)},",
        f"{sangria}  fondoHex: {_cadena_ts(par.fondo.color.hex)},",
        f"{sangria}  ratio: {par.ratio},",
        f"{sangria}  veredicto: {_cadena_ts(par.veredicto)},",
        f"{sangria}  regla: {_cadena_ts(par.regla)},",
        f"{sangria}}},",
    ]


