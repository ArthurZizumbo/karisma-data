def draw_box(ax, x, y, w, h, facecolor, edgecolor=COLOR_NAVY, lw=1.4,
             zorder=5):
    """Draw a plain rectangle used as a node of the diagrams."""
    patch = Rectangle((x, y), w, h, facecolor=facecolor, edgecolor=edgecolor,
                      lw=lw, zorder=zorder)
    ax.add_patch(patch)
    return patch


def draw_change_band(ax, x, y, w, h, zorder=7):
    """Draw the solid amber band that flags a node changed after the test.

    A solid band survives a black and white printout (it turns into a dark
    strip) without laying a texture behind the label, so the text stays
    readable.
    """
    ax.add_patch(Rectangle((x, y), w, h, facecolor=COLOR_AMBER,
                           edgecolor=COLOR_AMBER, lw=0.8, zorder=zorder))


def draw_elbow(ax, x0, y0, x1, y1, color=COLOR_MUTED, lw=1.2, ls='-',
               zorder=2):
    """Draw an orthogonal connector: vertical drop, then horizontal run."""
    ax.plot([x0, x0], [y0, y1], color=color, lw=lw, ls=ls, zorder=zorder,
            solid_capstyle='butt')
    ax.plot([x0, x1], [y1, y1], color=color, lw=lw, ls=ls, zorder=zorder,
            solid_capstyle='butt')


def generar_matriz_competitiva():
    """Genera un gráfico de gradiente de características vs costo/esfuerzo"""
    fig, ax = plt.subplots(figsize=(10, 6))

    # Datos simulados de competidores
    competidores = ['Karisma Data', 'Bloomberg Terminal',
                    'Herramientas BI (Power BI, Pyramid)',
                    'Bases Aisladas / Excel', 'Silos Departamentales']
    x_cost = [4, 9, 5, 2, 3]   # Costo/Esfuerzo
    y_feat = [9, 10, 7, 3, 4]  # Características para la Institución
    sizes = [800, 500, 500, 400, 400]
    colors = [COLOR_AMBER, COLOR_NAVY, COLOR_SKY, COLOR_MUTED, COLOR_MUTED]

    ax.scatter(x_cost, y_feat, s=sizes, c=colors, alpha=0.8, edgecolors='w',
               linewidth=2)

    # Etiquetas
    for i, txt in enumerate(competidores):
        ax.annotate(txt, (x_cost[i], y_feat[i]), xytext=(0, -15),
                    textcoords='offset points', ha='center', va='top',
                    fontweight='bold' if txt == 'Karisma Data' else 'normal',
                    color=COLOR_NAVY)

    ax.set_title('Gradiente de Postura Competitiva (Institucional)',
                 fontsize=16, fontweight='bold', color=COLOR_NAVY, pad=20)
    ax.set_xlabel('Costo y Esfuerzo de Implementación', fontsize=12,
                  color=COLOR_NAVY)
    ax.set_ylabel('Funcionalidad Específica (Datos Macroeconómicos/Silos)',
                  fontsize=12, color=COLOR_NAVY)

    ax.set_xlim(0, 10)
    ax.set_ylim(0, 11)

    ax.grid(True, linestyle='--', alpha=0.5, color=COLOR_MUTED)
    ax.spines['top'].set_visible(False)
    ax.spines['right'].set_visible(False)
    ax.spines['left'].set_color(COLOR_NAVY)
    ax.spines['bottom'].set_color(COLOR_NAVY)

    plt.tight_layout()
    plt.savefig('figuras/a3_matriz_competitiva.png', dpi=300,
                bbox_inches='tight')
    plt.close()


